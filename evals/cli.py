"""
AegisRAG Evaluation CLI
Runs quantitative offline evaluation suites:
  1. Guardrails binary safety suite (Precision, Recall, Accuracy)
  2. Live pipeline execution over golden samples
  3. RAGAS 0.4.3 multi-metric judge suite (Faithfulness, Relevancy, Precision, Recall, Correctness, Jaccard Tool Correctness)
Outputs formatted Markdown & JSON reports to evals/reports/
"""

import os
import sys
import json
import time
import asyncio
import argparse
from datetime import datetime

from evals.pipeline import run_pipeline, load_golden_dataset, save_results
from evals.guardrails_eval import run_guardrails_eval, compute_guardrails_metrics
from evals.metrics import run_all_metrics


def generate_markdown_report(
    guardrails_metrics: dict,
    guardrails_samples: list,
    ragas_results: dict,
    output_path: str
) -> str:
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    # Compute RAGAS averages
    ragas_summary = {}
    for metric_name, df in ragas_results.items():
        if metric_name in df.columns:
            ragas_summary[metric_name] = round(float(df[metric_name].mean()), 3)

    md = f"""# AegisRAG Evaluation Report
**Timestamp:** {timestamp}  
**Dataset:** 15 Technical RAG Golden Samples + 6 Guardrail Adversarial Tests

---

## 1. Guardrail Safety Confusion Matrix (Gate 1)

| Metric | Score | Details |
| :--- | :--- | :--- |
| **Accuracy** | **{guardrails_metrics.get('accuracy', 0.0) * 100:.1f}%** | ({guardrails_metrics.get('correct', 0)} / {guardrails_metrics.get('total', 0)} correct) |
| **Precision** | **{guardrails_metrics.get('precision', 0.0) * 100:.1f}%** | TP: {guardrails_metrics.get('tp', 0)}, FP: {guardrails_metrics.get('fp', 0)} |
| **Recall** | **{guardrails_metrics.get('recall', 0.0) * 100:.1f}%** | TP: {guardrails_metrics.get('tp', 0)}, FN: {guardrails_metrics.get('fn', 0)} |
| **True Negatives** | **{guardrails_metrics.get('tn', 0)}** | Legitimate queries allowed through |

### Guardrail Sample Breakdown
| ID | Type | Expected Blocked | Actual Result | Status |
| :--- | :--- | :--- | :--- | :--- |
"""
    for s in guardrails_samples:
        status_icon = "✅ Pass" if s.get("result") in ("TP", "TN") else "❌ Fail"
        md += f"| {s.get('id')} | {s.get('type')} | {s.get('expected_blocked')} | {s.get('result')} | {status_icon} |\n"

    md += f"""
---

## 2. RAGAS & Agentic Quality Metrics (Gate 2)

| Metric | Score | Target | Assessment |
| :--- | :--- | :--- | :--- |
| **Faithfulness** | **{ragas_summary.get('faithfulness', 'N/A')}** | ≥ 0.85 | {'✅ Optimal' if (ragas_summary.get('faithfulness') or 0) >= 0.85 else '⚠️ Needs Attention'} |
| **Answer Relevancy** | **{ragas_summary.get('answer_relevancy', 'N/A')}** | ≥ 0.85 | {'✅ Optimal' if (ragas_summary.get('answer_relevancy') or 0) >= 0.85 else '⚠️ Needs Attention'} |
| **Context Precision** | **{ragas_summary.get('context_precision', 'N/A')}** | ≥ 0.80 | {'✅ Optimal' if (ragas_summary.get('context_precision') or 0) >= 0.80 else '⚠️ Needs Attention'} |
| **Context Recall** | **{ragas_summary.get('context_recall', 'N/A')}** | ≥ 0.80 | {'✅ Optimal' if (ragas_summary.get('context_recall') or 0) >= 0.80 else '⚠️ Needs Attention'} |
| **Answer Correctness** | **{ragas_summary.get('answer_correctness', 'N/A')}** | ≥ 0.80 | {'✅ Optimal' if (ragas_summary.get('answer_correctness') or 0) >= 0.80 else '⚠️ Needs Attention'} |
| **Tool Correctness (Jaccard)** | **{ragas_summary.get('tool_correctness', 'N/A')}** | ≥ 0.90 | {'✅ Optimal' if (ragas_summary.get('tool_correctness') or 0) >= 0.90 else '⚠️ Needs Attention'} |

---
*Report auto-generated by AegisRAG evaluation pipeline.*
"""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(md)
    return md


def main():
    parser = argparse.ArgumentParser(description="AegisRAG Automated Evaluation Runner")
    parser.add_argument("--mode", choices=["all", "guardrails", "pipeline", "ragas"], default="all")
    parser.add_argument("--dataset", default=None, help="Path to custom golden dataset JSON")
    parser.add_argument("--out-dir", default="evals/reports", help="Directory for generated reports")
    parser.add_argument("--fail-under", type=float, default=None, help="Fail with exit code 1 if average score < threshold")

    args = parser.parse_args()

    dataset = load_golden_dataset() if not args.dataset else json.load(open(args.dataset))
    timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")

    guardrails_metrics = {}
    enriched_guardrails = []
    ragas_results = {}

    if args.mode in ("all", "guardrails"):
        print("\n🛡️ [1/2] Running Guardrails Evaluation...")
        enriched_guardrails = run_guardrails_eval(dataset.get("guardrails_samples", []))
        guardrails_metrics = compute_guardrails_metrics(enriched_guardrails)
        print(f"   Accuracy: {guardrails_metrics['accuracy']:.3f} | Precision: {guardrails_metrics['precision']:.3f} | Recall: {guardrails_metrics['recall']:.3f}")

    if args.mode in ("all", "pipeline", "ragas"):
        print("\n🚀 [2/2] Running Live Pipeline Query Execution...")
        enriched_dataset = run_pipeline(dataset)
        
        # Save enriched responses
        raw_output_path = os.path.join(args.out_dir, f"pipeline_results_{timestamp_str}.json")
        save_results(enriched_dataset, raw_output_path)
        print(f"   Saved raw pipeline answers to {raw_output_path}")

        if args.mode in ("all", "ragas"):
            print("\n🧪 Scoring with RAGAS 0.4.3 & Jaccard Tool Correctness...")
            ragas_results = asyncio.run(run_all_metrics(enriched_dataset))

    # Generate Markdown report
    report_path = os.path.join(args.out_dir, f"eval_report_{timestamp_str}.md")
    report_md = generate_markdown_report(guardrails_metrics, enriched_guardrails, ragas_results, report_path)
    print(f"\n📊 Evaluation Report generated at: {report_path}")
    print("\n" + report_md)

    if args.fail_under is not None:
        scores = []
        if guardrails_metrics:
            scores.append(guardrails_metrics.get("accuracy", 0.0))
        for metric, df in ragas_results.items():
            if metric in df.columns:
                scores.append(df[metric].mean())
        
        if scores:
            avg_score = sum(scores) / len(scores)
            if avg_score < args.fail_under:
                print(f"❌ CI Check Failed: Average score {avg_score:.3f} is below threshold {args.fail_under}")
                sys.exit(1)
            else:
                print(f"✅ CI Check Passed: Average score {avg_score:.3f} >= {args.fail_under}")


if __name__ == "__main__":
    main()
